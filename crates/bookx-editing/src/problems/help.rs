//! Plain-language help for every check id: what the message means, why it matters, how to fix it.
//! A pure table, so it can be tested without a window.

/// The three paragraphs shown next to a selected problem.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Help {
    pub meaning: &'static str,
    pub why: &'static str,
    pub how: &'static str,
}

/// Help for a check id (`None` for ids this version does not know).
pub fn help(id: &str) -> Option<Help> {
    HELP.iter()
        .find(|(i, ..)| *i == id)
        .map(|(_, meaning, why, how)| Help { meaning, why, how })
}

/// Every id that has help.
pub fn ids() -> impl Iterator<Item = &'static str> {
    HELP.iter().map(|h| h.0)
}

