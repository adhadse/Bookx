#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_rule_has_help_and_every_help_a_rule() {
        let mut all: Vec<&str> = crate::validate::RULES
            .iter()
            .chain(crate::validate::EXTRA_RULES.iter())
            .map(|r| r.id)
            .collect();
        all.extend(crate::problems::CHECK_RULES.iter().map(|r| r.0));
        for id in &all {
            let h = help(id).unwrap_or_else(|| panic!("no help for {id}"));
            for t in [h.meaning, h.why, h.how] {
                assert!(t.len() > 10 && t.len() < 400, "{id}: {t}");
            }
        }
        for id in ids() {
            assert!(all.contains(&id), "help for unknown id {id}");
        }
        let mut sorted: Vec<&str> = ids().collect();
        sorted.sort();
        sorted.dedup();
        assert_eq!(sorted.len(), ids().count(), "an id has two help texts");
    }

    #[test]
    fn help_is_plain_language() {
        for id in ids() {
            let h = help(id).unwrap();
            assert!(h.meaning.ends_with(['.', '?']), "{id}");
            assert!(h.how.ends_with(['.', '?']), "{id}");
        }
        assert!(help("NOPE-1").is_none());
    }
}
