"""Comics in the real GNOME session: real double-click, keys, wheel and drags. Imported by scenarios.py.
The comics are generated by `cargo run -p bookx-comic --example make_test_comics` (see docs/test-books.md):
every panel of a page has its own tint (red, green, blue, yellow in reading order), so what is on the
screen can be told from the screenshot."""
import re
import time

from harness import Skip, scenario


def red(r, g, b):
    return r > g + 25 and r > b + 25


def green(r, g, b):
    return g > r + 25 and g > b + 25


def blue(r, g, b):
    return b > r + 30 and b > g + 15


def yellow(r, g, b):
    return r > b + 40 and g > b + 35 and abs(r - g) < 0.25 * r


def label(c):
    """'Page N of M' (or 'Pages N–M of M') of the footer: the first number."""
    for n in c.find("label", rx=r"^Pages? \d+"):
        m = re.match(r"^Pages? (\d+)", n.name)
        if m:
            return int(m.group(1))
    return None


def area(c):
    """The page area has no accessible node: it is the window between the title bar (whose subtitle
    says the page) and the footer (whose label says it again)."""
    for _ in range(20):
        labels = sorted(c.find("label", rx=r"^Pages? \d+"), key=lambda n: n.box[1])
        frames = c.find("frame")
        if len(labels) >= 2 and frames:
            break
        time.sleep(0.5)
    else:
        return None
    sub, foot = labels[0], labels[-1]
    x0, _, x1, _ = c.screen_box(frames[0])
    top = c.screen_box(sub)[3] + 12
    bottom = c.screen_box(foot)[1] - 14
    return (x0 + 4, top, x1 - 4, bottom)


def colours(c, box, tag=None):
    img = c.image(tag)
    return {name: c.count_pixels(img, box, f) for name, f in (("red", red), ("green", green), ("blue", blue), ("yellow", yellow))}


def page_point(box, fx, fy, w=400, h=600):
    """The screen point at a fraction of a page that is fitted to the box."""
    bw, bh = box[2] - box[0], box[3] - box[1]
    s = min(bw / w, bh / h)
    pw, ph = w * s, h * s
    return box[0] + (bw - pw) / 2 + fx * pw, box[1] + (bh - ph) / 2 + fy * ph


def open_comic(c, title, books=("comic",), settings=""):
    if not c.books.get(books[0]):
        raise Skip("the generated test comics are not available (see docs/test-books.md)")
    c.start(books=books, settings=settings)
    if not c.check(f"{title} opens from the library", c.open_book(title)):
        return None
    time.sleep(2.0)
    box = area(c)
    c.check("the comic page area is there", box)
    c.sb.move_to((box[0] + box[2]) // 2, (box[1] + box[3]) // 2)
    return box


@scenario
def comic_smart_zoom(c):
    """Double-click zooms to the panel under the pointer, again goes back; guided view with Space and
    Shift+Space steps through the panels in reading order and over the page."""
    box = open_comic(c, "Gutter Tales")
    if not box:
        return
    c.check("it opens on page 1", label(c) == 1, str(label(c)))
    c.sb.key("Right")
    time.sleep(0.8)
    c.check("the Right arrow turns to page 2", label(c) == 2, str(label(c)))
    time.sleep(1.0)
    base = colours(c, box, "grid")
    c.shot("grid")
    c.check("the page with four panels shows all four tints", min(base.values()) > 1500, str(base))

    # a real double-click on the top left (red) panel
    x, y = page_point(box, 0.26, 0.25)
    c.sb.double_click(x, y)
    time.sleep(1.5)
    zoomed = colours(c, box, "panel-red")
    c.check("double-click zooms to the panel: the lower panels are gone", zoomed["blue"] + zoomed["yellow"] < 0.05 * (base["blue"] + base["yellow"]), str(zoomed))
    c.check("and the red panel is larger than before", zoomed["red"] > base["red"] * 1.8, f"{base['red']} -> {zoomed['red']}")

    c.sb.double_click((box[0] + box[2]) // 2, (box[1] + box[3]) // 2)
    time.sleep(1.5)
    back = colours(c, box, "panel-back")
    c.check("double-click again shows the whole page", min(back.values()) > 1500 and back["red"] < zoomed["red"], str(back))

    # a real double-click on the bottom right (yellow) panel
    c.sb.double_click(*page_point(box, 0.74, 0.75))
    time.sleep(1.5)
    z2 = colours(c, box, "panel-yellow")
    c.check("a double-click on the bottom right panel shows the lower half", z2["red"] + z2["green"] < 0.05 * (base["red"] + base["green"]) and z2["yellow"] > base["yellow"] * 1.8, str(z2))
    c.sb.double_click((box[0] + box[2]) // 2, (box[1] + box[3]) // 2)
    time.sleep(1.2)

    # guided view: G, then Space goes panel by panel
    c.sb.key("g")
    time.sleep(0.4)
    for n in range(3):
        c.sb.key("space")
        time.sleep(1.3)
    third = colours(c, box, "guided-3")
    c.check("Space three times: on the bottom left panel (nothing of the top row)", third["red"] + third["green"] < 0.05 * (base["red"] + base["green"]) and third["blue"] > base["blue"] * 1.8, str(third))
    c.sb.key("space")
    time.sleep(1.3)
    c.sb.key("space")
    time.sleep(1.5)
    c.check("Space after the fourth panel turns to page 3", label(c) == 3, str(label(c)))
    c.shot("guided-next-page")
    c.sb.key("space", ("Shift",))
    time.sleep(1.5)
    c.check("Shift+Space goes back to page 2", label(c) == 2, str(label(c)))
    back4 = colours(c, box, "guided-back")
    c.check("at its last panel (yellow, bottom right)", back4["red"] + back4["green"] < 0.05 * (base["red"] + base["green"]) and back4["yellow"] > base["yellow"] * 1.8, str(back4))


@scenario
def comic_manga(c):
    """A manga opens right to left: Left goes forward, a click near the left edge goes forward, a swipe to the left
    goes back, the r key turns the direction round."""
    box = open_comic(c, "Right Way", books=("manga",))
    if not box:
        return
    c.check("it opens on page 1", label(c) == 1, str(label(c)))
    c.sb.key("Left")
    time.sleep(0.8)
    c.check("Left goes to page 2 in a right-to-left book", label(c) == 2, str(label(c)))
    c.sb.key("Right")
    time.sleep(0.8)
    c.check("Right goes back to page 1", label(c) == 1, str(label(c)))
    # a real click near the left edge of the page area
    c.sb.click(box[0] + 40, (box[1] + box[3]) // 2)
    time.sleep(1.2)
    c.check("a click near the left edge goes forward", label(c) == 2, str(label(c)))
    c.shot("manga-page2")
    # a real swipe: drag to the left on a fitted page goes back in a right-to-left book
    cy = (box[1] + box[3]) // 2
    mid = (box[0] + box[2]) // 2
    c.sb.drag(mid + 200, cy, mid - 200, cy)
    time.sleep(1.0)
    c.shot("after-swipe")
    c.check("a swipe to the left goes back", label(c) == 1, str(label(c)))
    c.sb.key("r")
    time.sleep(0.6)
    c.sb.key("Left")
    time.sleep(0.8)
    c.check("after r (left to right) the Left arrow does not go forward", label(c) == 1, str(label(c)))
    c.sb.key("Right")
    time.sleep(0.8)
    c.check("Right goes forward now", label(c) == 2, str(label(c)))
    # the choice is remembered for the book
    c.restart_app()
    time.sleep(1.0)
    c.check("it opens again", c.open_book("Right Way"))
    time.sleep(1.5)
    c.sb.key("Left")
    time.sleep(0.8)
    p = label(c)
    c.check("left to right is remembered for this book (Left does not go on)", p is not None and p <= 2, str(p))


@scenario
def comic_modes_input(c):
    """Layouts and thumbnails with real input: M cycles the layout, the wheel scrolls the webtoon strip and
    a click on a thumbnail goes to its page."""
    box = open_comic(c, "Gutter Tales")
    if not box:
        return
    btn = c.wait_node(rx=r"^View options$", timeout=6)
    c.check("the View options button is there", btn)
    if btn:
        c.click_node(btn)
        time.sleep(1.0)
        c.shot("view-options")
        c.check("the popover offers the layouts", c.find(rx=r"^Two pages$") and c.find(rx=r"Right to left"))
        c.sb.key("Escape")
        time.sleep(0.6)
    c.sb.key("m")
    time.sleep(1.0)
    c.sb.key("Right")
    time.sleep(0.8)
    two = label(c)
    c.check("two-page layout: the cover is alone, the next screen starts with page 2", two == 2, str(two))
    c.shot("two-pages")
    c.sb.key("m")
    time.sleep(1.2)
    c.shot("webtoon")
    cx, cy = (box[0] + box[2]) // 2, (box[1] + box[3]) // 2
    before = label(c)
    for _ in range(4):
        c.sb.scroll(30, cx, cy)
        time.sleep(0.5)
    time.sleep(1.0)
    after = label(c)
    c.check("the wheel scrolls the strip on to a later page", before is not None and after is not None and after > before, f"{before} -> {after}")
    c.sb.key("F9")
    time.sleep(1.5)
    c.shot("thumbs")
    row = c.wait_node(rx=r"^Page 3$", timeout=6)
    c.check("the thumbnail strip lists the pages", row)
    if row:
        c.click_node(row)
        time.sleep(1.2)
        c.check("a click on a thumbnail goes to that page", label(c) == 3, str(label(c)))
    c.sb.key("Home")
    time.sleep(1.0)
    c.check("Home goes to the first page", label(c) == 1, str(label(c)))


@scenario
def comic_dark_and_light(c):
    """The space around a page follows the desktop's light or dark style and the page is not recoloured."""
    box = open_comic(c, "Gutter Tales", settings="[org/gnome/desktop/interface]\ncolor-scheme='prefer-dark'\n")
    if not box:
        return
    c.sb.key("Right")
    time.sleep(1.2)
    img = c.image("dark")
    px = img.load()
    margin = px[box[0] + 20, (box[1] + box[3]) // 2]
    c.check("dark style: the space beside the page is dark", sum(margin) < 150, str(margin))
    shown = colours(c, box)
    c.check("the panels keep their colours", min(shown.values()) > 1500, str(shown))
