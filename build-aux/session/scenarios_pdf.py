"""PDF reading in the real GNOME session: real wheel, keys and pointer. Imported by scenarios.py.
The PDF is generated by `cargo run -p bookx-pdf --example make_test_pdfs` (see docs/test-books.md)."""
import re
import time

from harness import Skip, scenario


def yellow(r, g, b):
    return r > 225 and g > 170 and b < 140


def dark(r, g, b):
    return r + g + b < 200


def caption(c):
    """The page caption of the footer: 'i (1 of 8)' -> the N of 'N of M'."""
    for n in c.find("label", rx=r"\(\d+ of \d+\)$|^\d+ of \d+$"):
        m = re.search(r"(\d+) of (\d+)\)?$", n.name)
        if m:
            return int(m.group(1))
    return None


@scenario
def pdf_reading(c):
    """A PDF opens as pages: ink on paper, wheel scrolling, zoom keys, a real drag selects text and
    highlights it, search finds a word on a far page."""
    if not c.books.get("pdf"):
        raise Skip("the test PDF is not available (see docs/test-books.md)")
    c.start(books=("pdf",))
    if not c.check("the PDF opens from the library", c.open_book("Fox Papers")):
        return
    # the page area itself has no accessible node; it is the window left of the vertical scroll bar
    bar = c.wait_node("scroll bar", "Scroll the pages", timeout=8)
    time.sleep(2.0)
    c.shot("page")
    if not c.check("the page view is there", bar):
        return
    bx0, by0, bx1, by1 = c.screen_box(bar)
    box = (0, by0, bx0, by1)
    img = c.image("p1")
    ink = c.count_pixels(img, box, dark)
    c.check("the first page is drawn with text on it", ink > 800, f"{ink} dark px")
    c.check("the footer says page 1", caption(c) == 1, str(caption(c)))

    # wheel scrolling moves through the pages
    cx, cy = (box[0] + box[2]) // 2, (box[1] + box[3]) // 2
    c.sb.scroll(40, cx, cy)
    time.sleep(1.5)
    c.check("the wheel scrolls on to a later page", (caption(c) or 0) >= 2, str(caption(c)))
    c.sb.key("Home")
    time.sleep(1.0)
    c.check("Home goes back to the first page", caption(c) == 1, str(caption(c)))

    # zoom with the keyboard changes the size of what is drawn
    before = c.count_pixels(c.image(), box, dark)
    for _ in range(3):
        c.sb.key("=", ("Control",))
        time.sleep(0.2)
    time.sleep(2.0)
    after = c.count_pixels(c.image("zoomed"), box, dark)
    c.check("Ctrl+plus enlarges the page", after != before, f"{before} -> {after}")
    c.sb.key("0", ("Control",))
    time.sleep(1.5)

    # a real drag across the first line of text: fit width scale = (width - 24) / 612
    scale = ((box[2] - box[0]) - 24) / 612.0
    x0 = box[0] + 12 + 72 * scale
    y = box[1] + 12 + (792 - 680) * scale - 4 * scale
    c.sb.drag(x0 + 2, y, x0 + 200 * scale, y)
    btn = c.wait_node("button", "Highlight Yellow", timeout=6)
    c.shot("selected")
    c.check("dragging over a line of the PDF selects text and opens the actions", btn)
    if btn:
        c.click_node(btn)
        time.sleep(1.0)
        img = c.image("highlighted")
        n = c.count_pixels(img, box, yellow)
        c.check("the highlight is painted on the page", n > 300, f"{n} yellow px")

    # search for a word that is only on page 5
    c.sb.key("f", ("Control",))
    time.sleep(0.6)
    c.sb.type("zyzzyva")
    time.sleep(3.0)
    c.sb.key("Return")
    time.sleep(1.5)
    c.shot("search")
    c.check("searching shows the page with the word (page 5)", caption(c) == 5, str(caption(c)))
