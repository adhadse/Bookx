"""Vertical writing in the real GNOME session: real pointer and keyboard, AT-SPI geometry, screenshots.
Imported by scenarios.py. The books are generated by build-aux/make-vertical-epubs.py (see docs/test-books.md)."""
import time

from harness import Skip, scenario
import atspi
from gi.repository import Atspi

from scenarios_a11y import page_node, page_text, text_iface


def book(c, key):
    path = c.books.get(key)
    if not path:
        raise Skip(f"{key} not available (see docs/test-books.md)")
    return path


def box_of(c, canvas, offset):
    """Screen rectangle (x, y, w, h) AT-SPI gives for the character at `offset` of the page text."""
    t = text_iface(canvas)
    r = Atspi.Text.get_character_extents(t, offset, Atspi.CoordType.WINDOW)
    ox, oy = atspi.ORIGIN
    return (r.x + ox, r.y + oy, r.width, r.height)


def centre(b):
    return (b[0] + b[2] / 2, b[1] + b[3] / 2)


def yellow(r, g, b):
    return r > 225 and g > 170 and b < 120


def clusters(img, box, pred, gap=6):
    """Vertical bands of pixels matching `pred` in the screen box: [(x0, x1, y0, y1)] left to right."""
    x0, y0, x1, y1 = box
    px = img.load()
    cols = {}
    for x in range(x0, min(x1, img.width)):
        ys = [y for y in range(y0, min(y1, img.height)) if pred(*px[x, y])]
        if ys:
            cols[x] = (min(ys), max(ys))
    out = []
    for x in sorted(cols):
        if out and x - out[-1][1] <= gap:
            o = out[-1]
            out[-1] = (o[0], x, min(o[2], cols[x][0]), max(o[3], cols[x][1]))
        else:
            out.append((x, x, cols[x][0], cols[x][1]))
    return out


@scenario
def vertical_reading(c):
    """A Japanese book with writing-mode: vertical-rl: columns, ruby, page turns, drag selection, highlights, search."""
    book(c, "vsynth")
    c.start(books=("vsynth",))
    if not c.check("the vertical book opens", c.open_book("縦書き")):
        return
    canvas = c.wait_node(None, rx=r", page text$", timeout=8)
    time.sleep(1.5)
    c.shot("page")
    if not c.check("the reading canvas is there", canvas):
        return
    canvas = page_node(c)
    box = c.screen_box(canvas)
    text = c.wait(lambda: page_text(c) or None, 8) or ""
    c.check("the text a screen reader reads starts with the heading, in reading order", text.startswith("縦書きのテスト\n春の朝、小さな図書館"),
            repr(text[:40]))
    c.check("the ruby annotations are not part of that text", "はる" not in text[:60], repr(text[:60]))

    # the geometry AT-SPI gives for characters is the geometry drawn: columns run down, the next one is to the left
    b0, b1, b20 = box_of(c, canvas, 0), box_of(c, canvas, 1), box_of(c, canvas, 20)
    cx = (box[0] + box[2]) / 2
    c.check("the first character is on the right-hand page (columns start at the right)", centre(b0)[0] > cx,
            f"{b0} canvas {box}")
    c.check("the second character is below the first, in the same column",
            b1[1] > b0[1] and abs(centre(b1)[0] - centre(b0)[0]) < b0[2], f"{b0} {b1}")
    c.check("a character further on is in a column to the left", centre(b20)[0] < centre(b0)[0] - b0[2] * 0.5, f"{b0} {b20}")
    c.check("a character box is taller than one line is thick for a 3 character range",
            Atspi.Text.get_range_extents(text_iface(canvas), 0, 3, Atspi.CoordType.WINDOW).height
            > Atspi.Text.get_range_extents(text_iface(canvas), 0, 3, Atspi.CoordType.WINDOW).width)

    img = c.image("p1")
    dark = lambda r, g, b: r + g + b < 200  # noqa: E731
    left_page = c.count_pixels(img, (box[0], box[1], int(cx) - 30, box[3]), dark)
    right_page = c.count_pixels(img, (int(cx) + 30, box[1], box[2], box[3]), dark)
    c.check("both pages are set with text", left_page > 2000 and right_page > 2000, f"{left_page} / {right_page}")
    # the first column hugs the right edge of the right page: dark pixels in the rightmost 10% of the canvas
    edge = c.count_pixels(img, (int(box[2] - (box[2] - box[0]) * 0.12), box[1], box[2], box[3]), dark)
    c.check("the first column is at the right edge of the page", edge > 300, f"{edge} dark px")

    # page turns: this book says page-progression-direction rtl, so Left goes forward
    p0 = (c.page_label() or (0, 0))[0]
    c.sb.key("Left")
    ok = c.wait(lambda: (c.page_label() or (0, 0))[0] != p0, 5)
    p1 = (c.page_label() or (0, 0))[0]
    c.check("the Left key turns to the next pages of a right-to-left book", ok and p1 > p0, f"{p0} -> {p1}")
    c.shot("p3")
    c.sb.key("Right")
    c.wait(lambda: (c.page_label() or (0, 0))[0] == p0, 5)
    c.check("the Right key goes back", (c.page_label() or (0, 0))[0] == p0, str(c.page_label()))

    # a real drag across two columns selects text in reading order
    canvas = page_node(c)
    a, b = box_of(c, canvas, 8), box_of(c, canvas, 60)
    # from the upper part of the 9th character to the lower part of the 61st: the selection is exactly 8..61
    c.sb.drag(centre(a)[0], a[1] + a[3] * 0.25, centre(b)[0], b[1] + b[3] * 0.75)
    btn = c.wait_node("button", "Highlight Yellow", timeout=5)
    c.shot("selected")
    c.check("dragging down one column and into the next selects text and opens the actions", btn)
    t = text_iface(canvas)
    sel = None
    if t and Atspi.Text.get_n_selections(t) > 0:
        r = Atspi.Text.get_selection(t, 0)
        sel = Atspi.Text.get_text(t, r.start_offset, r.end_offset)
    c.check("the selection is exposed to AT-SPI as that range of the page text",
            sel is not None and 40 <= len(sel) <= 60 and sel in text, repr(sel))
    c.check("the selected text is exactly the characters between the two points, in logical order",
            sel is not None and sel == text[8:61], repr(sel))
    if btn:
        c.click_node(btn)
        time.sleep(0.9)
        img = c.image("highlighted")
        bands = clusters(img, box, yellow)
        tall = [bd for bd in bands if bd[3] - bd[2] >= 80 and bd[1] - bd[0] >= 12]
        c.check("the highlight is painted column by column (tall yellow bands)", len(tall) >= 2, str(bands[:6]))
        c.shot("highlight")

    # search: matches are painted in the vertical geometry too
    c.sb.key("Escape")  # closes the actions of the selection (a second one would leave the book)
    time.sleep(0.8)
    c.sb.key("f", ("Control",))
    entry = c.wait_node("search text", timeout=6) or c.wait_node("entry", timeout=3)
    if c.check("Ctrl+F opens the search entry", entry):
        c.click_node(entry)
        c.sb.type("Hello")  # AT-SPI key events carry ASCII only
        c.sb.key("Return")
        time.sleep(2.0)
        c.sb.key("Return")
        time.sleep(1.0)
        c.shot("search")
        img = c.image("search-hits")
        # the match that is shown is orange, the others pale yellow; both sit behind the glyphs
        orange = lambda r, g, b: r > 240 and 110 < g < 195 and 30 < b < 140  # noqa: E731
        hits = clusters(img, box, orange)
        c.check("a search match is painted over its characters: a band taller than it is wide, one column thick",
                any(h[3] - h[2] > 1.4 * (h[1] - h[0]) and h[3] - h[2] >= 40 for h in hits), str(hits[:6]))
    c.check("the app is alive", c.is_alive())


@scenario
def vertical_aozora(c):
    """A real book: Natsume Soseki, Wagahai wa neko de aru, chapters 1-3 (Aozora Bunko, public domain), with ruby."""
    book(c, "vneko")
    c.start(books=("vneko",))
    if not c.check("the book opens", c.open_book("吾輩")):
        return
    canvas = c.wait_node(None, rx=r", page text$", timeout=8)
    time.sleep(2.0)
    c.shot("page")
    if not canvas:
        c.check("the reading canvas is there", False)
        return
    canvas = page_node(c)
    box = c.screen_box(canvas)
    text = c.wait(lambda: page_text(c) or None, 8) or ""
    c.check("the page text is the novel, ruby left out", "吾輩は猫である。名前はまだ無い。" in text and "わがはい" not in text, repr(text[:50]))
    b0 = box_of(c, canvas, 0)
    c.check("the chapter number is in the top right corner", centre(b0)[0] > (box[0] + box[2]) / 2 and b0[1] < box[1] + 120, str(b0))
    img = c.image("p1")
    dark = lambda r, g, b: r + g + b < 200  # noqa: E731
    c.check("the pages are full of text", c.count_pixels(img, box, dark) > 8000)
    p0 = (c.page_label() or (0, 0))
    c.check("the book has many pages", p0[1] > 5, str(p0))
    for _ in range(3):
        c.sb.key("Left")
        time.sleep(0.4)
    c.shot("page4")
    p1 = (c.page_label() or (0, 0))
    c.check("three Left presses move on in the book", p1[0] > p0[0], f"{p0} -> {p1}")
    t2 = page_text(c) or ""
    c.check("the next pages continue the text", t2 and t2 != text and "わがはい" not in t2)
    c.check("the app is alive", c.is_alive())
