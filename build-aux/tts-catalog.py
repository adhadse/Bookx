#!/usr/bin/env python3
"""Regenerates crates/bookx-tts/src/catalog_data.rs: the download list of read aloud.

Every file is pinned by its SHA-256 (the app refuses a download that does not match), so
updating a model or a voice means running this script and reviewing the diff:

    python3 build-aux/tts-catalog.py             # everything
    python3 build-aux/tts-catalog.py --only-ort  # just the ONNX Runtime lines

It needs network access. Big files take their hash from the Hugging Face API (LFS object id);
small files and the ONNX Runtime archives are downloaded once and hashed here.
"""
import hashlib
import io
import json
import re
import struct
import sys
import tarfile
import urllib.request
import zlib
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "crates/bookx-tts/src/catalog_data.rs"
ORT = "1.31.1"
# The same official libonnxruntime.so is also inside the NuGet package (a 160 MB zip of all platforms on a fast
# CDN). The app reads only the one member it needs with HTTP Range requests, so it downloads about the same
# 10 MB as the GitHub archive. Both origins are pinned to the SAME hash of the extracted library.
NUGET = f"https://globalcdn.nuget.org/packages/microsoft.ml.onnxruntime.{ORT}.nupkg"
NUGET_MEMBERS = {"x64": "runtimes/linux-x64/native/libonnxruntime.so", "aarch64": "runtimes/linux-arm64/native/libonnxruntime.so"}
KOKORO_REPO = "onnx-community/Kokoro-82M-v1.0-ONNX"
PIPER_REPO = "rhasspy/piper-voices"
PIPER = [
    "en/en_US/lessac/medium", "en/en_US/amy/medium", "en/en_US/ryan/high", "en/en_GB/alba/medium",
    "de/de_DE/thorsten/medium", "fr/fr_FR/siwis/medium", "es/es_ES/davefx/medium",
    "it/it_IT/paola/medium", "pt/pt_BR/faber/medium", "nl/nl_NL/mls/medium",
    "ru/ru_RU/irina/medium", "pl/pl_PL/gosia/medium", "cs/cs_CZ/jirka/medium",
    "tr/tr_TR/dfki/medium",
]


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": "bookx-tts-catalog"})
    with urllib.request.urlopen(req, timeout=300) as r:
        return r.read()


def get_range(url, a, b):
    req = urllib.request.Request(url, headers={"User-Agent": "bookx-tts-catalog", "Range": f"bytes={a}-{b}"})
    with urllib.request.urlopen(req, timeout=300) as r:
        assert r.status == 206, r.status
        return r.read()


def zip_member(url):
    """{name: (compressed size, size, crc, local header offset)} of a remote zip, from its central directory."""
    total = int(urllib.request.urlopen(urllib.request.Request(url, headers={"Range": "bytes=0-0"})).headers["Content-Range"].split("/")[1])
    tail = get_range(url, max(0, total - 200000), total - 1)
    i = tail.rfind(b"PK\x05\x06")
    _, _, _, n, _, cdsize, cdoff, _ = struct.unpack("<IHHHHIIH", tail[i:i + 22])
    cd = get_range(url, cdoff, cdoff + cdsize - 1)
    out, p = {}, 0
    while p + 46 <= len(cd) and struct.unpack("<I", cd[p:p + 4])[0] == 0x02014B50:
        (_, _, _, flags, comp, _, _, crc, csize, usize, nl, el, cl, _, _, _, lho) = struct.unpack("<IHHHHHHIIIHHHHHII", cd[p:p + 46])
        out[cd[p + 46:p + 46 + nl].decode()] = (csize, usize, crc, lho, comp)
        p += 46 + nl + el + cl
    return out


def nuget_lib(url, member, info):
    csize, usize, crc, lho, comp = info
    assert comp == 8, "the member is not deflated"
    head = get_range(url, lho, lho + 29)
    nl, el = struct.unpack("<HH", head[26:30])
    raw = get_range(url, lho + 30 + nl + el, lho + 30 + nl + el + csize - 1)
    data = zlib.decompress(raw, -15)
    assert len(data) == usize and zlib.crc32(data) == crc
    return data


def tree(repo, path=""):
    return json.loads(get(f"https://huggingface.co/api/models/{repo}/tree/main/{path}"))


def revision(repo):
    return json.loads(get(f"https://huggingface.co/api/models/{repo}"))["sha"]


def sha_of(repo, rev, entry):
    lfs = entry.get("lfs")
    if lfs:
        return lfs["oid"]
    return hashlib.sha256(get(f"https://huggingface.co/{repo}/resolve/{rev}/{entry['path']}")).hexdigest()


def q(s):
    return json.dumps(s, ensure_ascii=False)


def only_ort():
    """Rewrites only the ONNX Runtime constants of catalog_data.rs (the models keep their pinned revision)."""
    global OUT
    full = OUT
    OUT = Path("/tmp/tts-catalog-ort.rs")
    main(ort_only=True)
    new = OUT.read_text()
    old = full.read_text()
    start = old.index("pub const ORT_X64")
    end = old.index("pub const ORT_VERSION")
    end = old.index("\n", end) + 1
    full.write_text(old[:start] + new + old[end:])
    print("updated the ONNX Runtime lines of", full)


def main(ort_only=False):
    out = ["// @generated by build-aux/tts-catalog.py. Do not edit by hand.\n"]
    # ONNX Runtime
    members = zip_member(NUGET)
    for arch in ("x64", "aarch64"):
        name = f"onnxruntime-linux-{arch}-{ORT}.tgz"
        url = f"https://github.com/microsoft/onnxruntime/releases/download/v{ORT}/{name}"
        data = get(url)
        out.append(f"pub const ORT_{arch.upper()}: (&str, &str, u64) = ({q(url)}, {q(hashlib.sha256(data).hexdigest())}, {len(data)});\n")
        # the library inside the archive, and the same library from NuGet
        tar = tarfile.open(fileobj=io.BytesIO(data), mode="r:gz")
        m = [x for x in tar.getmembers() if x.isfile() and x.name.endswith(f"/lib/libonnxruntime.so.{ORT}")][0]
        lib = tar.extractfile(m).read()
        sha = hashlib.sha256(lib).hexdigest()
        out.append(f"/// (sha256, size) of the extracted libonnxruntime.so, the same from every origin.\n")
        out.append(f"pub const ORT_LIB_{arch.upper()}: (&str, u64) = ({q(sha)}, {len(lib)});\n")
        info = members[NUGET_MEMBERS[arch]]
        nug = nuget_lib(NUGET, NUGET_MEMBERS[arch], info)
        assert hashlib.sha256(nug).hexdigest() == sha, "NuGet and GitHub ship different libraries: pin both"
        out.append("/// (member, compressed size) of the library inside the NuGet package, read with Range requests.\n")
        out.append(f"pub const ORT_NUGET_{arch.upper()}: (&str, u64) = ({q(NUGET_MEMBERS[arch])}, {info[0]});\n")
    out.append(f"pub const ORT_NUGET_URL: &str = {q(NUGET)};\n")
    out.append(f"pub const ORT_VERSION: &str = {q(ORT)};\n")
    if ort_only:
        OUT.write_text("".join(out[1:]))
        return

    # Kokoro
    rev = revision(KOKORO_REPO)
    out.append(f"pub const KOKORO_REV: &str = {q(rev)};\n")
    models = {e["path"]: e for e in tree(KOKORO_REPO, "onnx")}
    for key, fname in (("INT8", "onnx/model_quantized.onnx"), ("FP32", "onnx/model.onnx")):
        e = models[fname]
        out.append(f"pub const KOKORO_{key}: (&str, &str, u64) = ({q(fname)}, {q(sha_of(KOKORO_REPO, rev, e))}, {e['size']});\n")
    vocab = json.loads(get(f"https://huggingface.co/{KOKORO_REPO}/resolve/{rev}/tokenizer.json"))["model"]["vocab"]
    out.append("/// The symbols Kokoro knows and their ids (tokenizer.json of the ONNX export).\n")
    out.append("pub const KOKORO_VOCAB: &[(char, i64)] = &[\n")
    for ch, i in sorted(vocab.items(), key=lambda x: x[1]):
        assert len(ch) == 1, ch
        out.append(f"    ({json.dumps(ch, ensure_ascii=False) if ch != chr(39) else chr(34)+chr(39)+chr(34)}, {i}),\n".replace('("', "('").replace('", ', "', ").replace("'\\\"'", "'\\\"'"))
    out.append("];\n")
    out.append("pub const KOKORO_VOICES: &[(&str, &str, u64)] = &[\n")
    for e in sorted(tree(KOKORO_REPO, "voices"), key=lambda x: x["path"]):
        name = e["path"].split("/")[-1][:-4]
        out.append(f"    ({q(name)}, {q(sha_of(KOKORO_REPO, rev, e))}, {e['size']}),\n")
    out.append("];\n")

    # Piper
    prev = revision(PIPER_REPO)
    out.append(f"pub const PIPER_REV: &str = {q(prev)};\n")
    out.append("/// (path, onnx sha256, onnx size, json sha256, json size, dataset licence)\n")
    out.append("pub const PIPER_VOICES: &[(&str, &str, u64, &str, u64, &str)] = &[\n")
    for p in PIPER:
        files = {e["path"].split("/")[-1]: e for e in tree(PIPER_REPO, p)}
        base = p.split("/")[-2]
        loc = p.split("/")[-3]
        quality = p.split("/")[-1]
        onnx = files[f"{loc}-{base}-{quality}.onnx"]
        js = files[f"{loc}-{base}-{quality}.onnx.json"]
        card = get(f"https://huggingface.co/{PIPER_REPO}/raw/{prev}/{p}/MODEL_CARD").decode()
        m = re.search(r"License:\s*(.+)", card)
        lic = m.group(1).strip() if m else "see the model card"
        out.append(f"    ({q(p)}, {q(sha_of(PIPER_REPO, prev, onnx))}, {onnx['size']}, {q(sha_of(PIPER_REPO, prev, js))}, {js['size']}, {q(lic)}),\n")
    out.append("];\n")
    OUT.write_text("".join(out))
    print("wrote", OUT)


if __name__ == "__main__":
    sys.exit(only_ort() if "--only-ort" in sys.argv else main())
